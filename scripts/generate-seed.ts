/**
 * Generates supabase/seed.sql from src/content/defaults.ts.
 *
 *   npm run seed:generate
 *
 * The seed is idempotent: every insert uses ON CONFLICT DO NOTHING, so
 * re-running it (locally or with `supabase db push --include-seed` against a
 * remote project) never overwrites edits made in the admin area.
 *
 * Runs with plain Node ≥ 22.18 (built-in TypeScript type stripping).
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  defaultCategories,
  defaultCertifications,
  defaultClaims,
  defaultLeaders,
  defaultOffices,
  defaultProcessSteps,
  defaultProjects,
  defaultRoutingRules,
  defaultSettings,
  defaultStats,
  defaultStrengths,
} from "../src/content/defaults.ts";

type SqlValue = string | number | boolean | null | undefined | string[] | object;

function lit(value: SqlValue): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "null";
  if (typeof value === "string") return `'${value.replace(/'/g, "''")}'`;
  if (Array.isArray(value) && value.every((v) => typeof v === "string")) {
    // Plain string lists map to text[] columns; arrays of objects fall through to jsonb.
    return value.length === 0 ? "'{}'::text[]" : `array[${value.map((v) => lit(v)).join(", ")}]::text[]`;
  }
  return `${lit(JSON.stringify(value))}::jsonb`;
}

function insert(table: string, rows: Record<string, SqlValue>[], conflict: string): string {
  if (rows.length === 0) return `-- ${table}: no rows\n`;
  const cols = Object.keys(rows[0]!);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict (${conflict}) do nothing;\n`;
}

